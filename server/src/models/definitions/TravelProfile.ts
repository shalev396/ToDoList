import type { TravelSettings } from '../../types/travel.js';

/**
 * A member's travel profile, one per member and workspace (`_id`: `<workspaceId>|<userId>`): their
 * settings, the length they set for each trip, their pins (an item's place, a calendar's or
 * project's default place), and where the daily pass stands. Private to its member.
 */
export interface TravelProfileData {
  /** `<workspaceId>|<userId>`. */
  id: string;
  workspaceId: string;
  ownerUserId: string;
  settings: TravelSettings;
  /** How long each trip takes, as he set it: minutes, by trip (`from|to|mode`, place ids). */
  tripLengths: Record<string, number>;
  /** A place pinned to an item (item id → place id). */
  itemPlaces: Record<string, string>;
  /** A calendar's or project's default place (container id → place id). */
  containerPlaces: Record<string, string>;
  /** The member has travel rules: the daily pass and item changes regenerate their legs. */
  hasTravel: boolean;
  /** The last day (`YYYY-MM-DD`, the workspace's zone) the daily pass regenerated them. */
  lastPassDay: string | null;
  updatedAt: Date;
}

export interface ITravelProfileRepository {
  /** The member's profile, made with these settings on first read. */
  findOrCreate(
    workspaceId: string,
    ownerUserId: string,
    defaults: { settings: TravelSettings },
  ): Promise<TravelProfileData>;
  /** Null when the member has no profile. */
  setSettings(
    workspaceId: string,
    ownerUserId: string,
    settings: TravelSettings,
  ): Promise<TravelProfileData | null>;
  /**
   * How long a trip takes (`from|to|mode`), as the member set it; `fillKey` (its way back) takes
   * the same minutes only when it has none yet. One write.
   */
  setTripLength(
    workspaceId: string,
    ownerUserId: string,
    tripKey: string,
    minutes: number,
    fillKey: string | null,
  ): Promise<TravelProfileData | null>;
  /** A pin of an item (`itemPlaces`) or a container (`containerPlaces`); null removes it. */
  setPin(
    workspaceId: string,
    ownerUserId: string,
    map: 'itemPlaces' | 'containerPlaces',
    id: string,
    placeId: string | null,
  ): Promise<TravelProfileData | null>;
  setLastPassDay(workspaceId: string, ownerUserId: string, day: string): Promise<void>;
  setHasTravel(workspaceId: string, ownerUserId: string, hasTravel: boolean): Promise<void>;
  /** A place was removed: the pins to it and the lengths of the trips from or to it go. */
  forgetPlace(workspaceId: string, ownerUserId: string, placeId: string): Promise<void>;
  /** A membership ended: the member's profile, hard-deleted. False when there was none. */
  delete(workspaceId: string, ownerUserId: string): Promise<boolean>;
  /** The workspace was deleted: every profile in it. Returns how many. */
  deleteForWorkspace(workspaceId: string): Promise<number>;
  /**
   * GLOBAL, every workspace: the daily travel pass only. The members with travel, and the day
   * their legs were last regenerated by it.
   */
  listWithTravel(): Promise<{ workspaceId: string; userId: string; lastPassDay: string | null }[]>;
  /** The members of one workspace with travel (after a sync there), by user id. */
  listWithTravelIn(workspaceId: string): Promise<string[]>;
  /** Whether the member has travel, read alone: false when they have no profile (none is made). */
  hasTravel(workspaceId: string, ownerUserId: string): Promise<boolean>;
}

export const TRAVEL_PROFILE_TABLE_NAME = 'TravelProfiles';
