/**
 * A member's travel profile, one per member and workspace, made on first read: their settings
 * (the spec's "global variables": going home in a window, the default mode), how long each trip
 * takes as he set it (from place, to place, mode → minutes: the only source of a leg's length, the
 * owner's decision of 2026-11-18; a trip he hasn't set is drawn with UNSET_TRIP_MINUTES), their
 * pins (an item's place, a calendar's or project's default place), whether they have travel at
 * all, and the last day the daily pass regenerated their legs. Private to its member; changes are
 * for editors and owners.
 *
 * The defaults are DEFAULT_TRAVEL_SETTINGS, deep-copied (it is frozen at every depth), and a
 * change is merged into a copy of the stored settings and checked whole (TravelSettingsSchema).
 */
import { NotFoundError } from '../../errors/NotFoundError.js';
import { ValidationError } from '../../errors/ValidationError.js';
import type { TravelProfileData } from '../../models/definitions/TravelProfile.js';
import { getTravelProfileRepository } from '../../models/index.js';
import {
  DEFAULT_TRAVEL_SETTINGS,
  TRAVEL_MODES,
  TRIP_MINUTES_MAX,
  TravelSettingsSchema,
  UNSET_TRIP_MINUTES,
  type TravelSettings,
  type TravelSettingsPatch,
  type TravelSettingsResponse,
} from '../../types/travel.js';
import type { Caller } from '../base/Caller.js';
import type { Owned } from '../base/contracts.js';
import { WorkspaceEntity } from '../base/WorkspaceEntity.js';
import type { Estimate, TripKey } from './DayPlanner.js';
import { Place } from './Place.js';

const DAY_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
/** An id a pin is keyed by (an item's, a container's). */
const ID_PATTERN = /^[A-Za-z0-9_:-]{1,200}$/;

/** A deep copy of the defaults (they are frozen at every depth). */
function defaultSettings(): TravelSettings {
  return structuredClone(DEFAULT_TRAVEL_SETTINGS);
}

/** 400 unless `key` is a trip: `from|to|mode`, two place ids and a mode. */
function checkedTrip(key: TripKey): TripKey {
  const [from, to, mode, ...rest] = key.split('|');
  const isId = (id: string | undefined): boolean => id !== undefined && ID_PATTERN.test(id);
  if (
    rest.length > 0 ||
    !isId(from) ||
    !isId(to) ||
    !(TRAVEL_MODES as readonly (string | undefined)[]).includes(mode)
  ) {
    throw new ValidationError('trip: from|to|mode, two places and a mode');
  }
  return key;
}

/** The same trip the other way: `to|from|mode`. */
function wayBack(key: TripKey): TripKey {
  const [from, to, mode] = key.split('|');
  return [to, from, mode].join('|');
}

function checkedId(id: string, field: string): string {
  if (!ID_PATTERN.test(id)) throw new ValidationError(`${field}: an id`);
  return id;
}

/** The values a partial change gives (one left out or undefined changes nothing). */
function given<T extends object>(change: T | undefined): Partial<T> {
  return Object.fromEntries(
    Object.entries(change ?? {}).filter(([, value]) => value !== undefined),
  ) as Partial<T>;
}

/** The stored settings when they are whole and valid; the defaults otherwise. */
function settingsOf(stored: unknown): TravelSettings {
  const parsed = TravelSettingsSchema.safeParse(stored);
  return parsed.success ? parsed.data : defaultSettings();
}

export class TravelProfile extends WorkspaceEntity<TravelProfileData> implements Owned {
  readonly #settings: TravelSettings;

  private constructor(data: TravelProfileData) {
    super(data);
    this.#settings = settingsOf(data.settings);
  }

  // ─── Reads ────────────────────────────────────────────────────────────────

  /** The caller's profile, made with the default settings on first read. */
  static async of(caller: Caller): Promise<TravelProfile> {
    const row = await (
      await getTravelProfileRepository()
    ).findOrCreate(caller.workspaceId, caller.userId, { settings: defaultSettings() });
    return new TravelProfile(row);
  }

  /**
   * GLOBAL, every workspace: the daily pass only. The members with travel, and the day their legs
   * were last regenerated by it.
   */
  static async listWithTravel(): Promise<
    { workspaceId: string; userId: string; lastPassDay: string | null }[]
  > {
    return (await getTravelProfileRepository()).listWithTravel();
  }

  /** The members of this workspace with travel (a sync there may have moved their anchors). */
  static async listWithTravelIn(workspaceId: string): Promise<string[]> {
    return (await getTravelProfileRepository()).listWithTravelIn(workspaceId);
  }

  /**
   * Whether the caller has travel: one read, and no profile is made for a member without one (an
   * item write asks this of every writer).
   */
  static async hasTravelFor(caller: Caller): Promise<boolean> {
    return (await getTravelProfileRepository()).hasTravel(caller.workspaceId, caller.userId);
  }

  /**
   * The caller's rules changed: whether they have any (the daily pass and item changes regenerate
   * only members with travel). Makes the profile if it is the first.
   */
  static async noteRules(caller: Caller, hasRules: boolean): Promise<void> {
    const profile = await TravelProfile.of(caller);
    if (profile.hasTravel === hasRules) return;
    await (
      await getTravelProfileRepository()
    ).setHasTravel(caller.workspaceId, caller.userId, hasRules);
  }

  get ownerUserId(): string {
    return this.data.ownerUserId;
  }

  isOwnedBy(userId: string): boolean {
    return this.data.ownerUserId === userId;
  }

  /** The member's settings (a copy: changing it changes nothing stored). */
  get settings(): TravelSettings {
    return structuredClone(this.#settings);
  }

  get hasTravel(): boolean {
    return this.data.hasTravel;
  }

  get lastPassDay(): string | null {
    return this.data.lastPassDay;
  }

  /** The pins: item id → place id. */
  get itemPlaces(): ReadonlyMap<string, string> {
    return new Map(Object.entries(this.data.itemPlaces));
  }

  /** The default places: container id → place id. */
  get containerPlaces(): ReadonlyMap<string, string> {
    return new Map(Object.entries(this.data.containerPlaces));
  }

  /**
   * As its member's own answers show it: the settings and the default places, never what else it
   * keeps (trip lengths, pins).
   */
  toSettingsView(): TravelSettingsResponse {
    return {
      settings: this.settings,
      containerPlaces: [...this.containerPlaces]
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([containerId, placeId]) => ({ containerId, placeId })),
    };
  }

  /** How long this trip takes as the member set it, in minutes; null while he hasn't. */
  tripMinutes(key: TripKey): number | null {
    const minutes = Object.hasOwn(this.data.tripLengths, key) ? this.data.tripLengths[key] : null;
    return typeof minutes === 'number' && Number.isFinite(minutes) && minutes > 0 ? minutes : null;
  }

  /**
   * The length every leg of this trip takes, every day and every occurrence alike: the one he set
   * (`set`), else UNSET_TRIP_MINUTES (`unset`).
   */
  tripLength(key: TripKey): Estimate {
    const minutes = this.tripMinutes(key);
    return minutes === null
      ? { minutes: UNSET_TRIP_MINUTES, source: 'unset' }
      : { minutes, source: 'set' };
  }

  // ─── Changes ──────────────────────────────────────────────────────────────

  /** Editors, their own: the settings with this change merged in, checked whole (400). */
  async updateSettings(caller: Caller, patch: TravelSettingsPatch): Promise<TravelProfile> {
    this.#authorize(caller);
    const current = this.settings;
    const merged = {
      goHome: { ...current.goHome, ...given(patch.goHome) },
      defaultMode: patch.defaultMode ?? current.defaultMode,
    };
    const parsed = TravelSettingsSchema.safeParse(merged);
    if (!parsed.success) {
      const [issue] = parsed.error.issues;
      throw new ValidationError(
        `settings.${issue?.path.join('.') ?? ''}: ${issue?.message ?? 'invalid'}`,
      );
    }
    return this.#asStored(
      await (
        await getTravelProfileRepository()
      ).setSettings(this.workspaceId, this.ownerUserId, parsed.data),
    );
  }

  /**
   * Editors, their own: how long a trip (`from|to|mode`) takes, every time. Every leg of that trip
   * takes it from the next regeneration on, every day and every occurrence, but the legs whose
   * times he set by hand. The way back (`to|from|mode`) starts with the same length when it has
   * none yet (the controller's ruling of 2026-11-19); one it has is left alone, and he can change
   * it on its own. More than 0 and at most a day. The one place a trip's length is set: a leg's
   * minutes, a mark's minutes, REST and MCP all come here.
   */
  async setTripLength(caller: Caller, key: TripKey, minutes: number): Promise<TravelProfile> {
    this.#authorize(caller);
    if (!Number.isFinite(minutes) || minutes <= 0 || minutes > TRIP_MINUTES_MAX) {
      throw new ValidationError(`minutes: more than 0 and at most ${String(TRIP_MINUTES_MAX)}`);
    }
    const trip = checkedTrip(key);
    const back = wayBack(trip);
    return this.#asStored(
      await (
        await getTravelProfileRepository()
      ).setTripLength(
        this.workspaceId,
        this.ownerUserId,
        trip,
        minutes,
        back === trip ? null : back,
      ),
    );
  }

  /** Editors, their own: an item's place (one of theirs: 400 otherwise); null unpins it. */
  async pinItemPlace(
    caller: Caller,
    itemId: string,
    placeId: string | null,
  ): Promise<TravelProfile> {
    return this.#pin(caller, 'itemPlaces', checkedId(itemId, 'itemId'), placeId);
  }

  /** Editors, their own: a calendar's or project's default place; null removes it. */
  async setContainerPlace(
    caller: Caller,
    containerId: string,
    placeId: string | null,
  ): Promise<TravelProfile> {
    return this.#pin(caller, 'containerPlaces', checkedId(containerId, 'containerId'), placeId);
  }

  /** The daily pass regenerated the member's legs on `day` (`YYYY-MM-DD`, the workspace's zone). */
  async markPassed(day: string): Promise<void> {
    if (!DAY_PATTERN.test(day)) throw new ValidationError('day: YYYY-MM-DD');
    await (
      await getTravelProfileRepository()
    ).setLastPassDay(this.workspaceId, this.ownerUserId, day);
  }

  // ─── Inside ───────────────────────────────────────────────────────────────

  async #pin(
    caller: Caller,
    map: 'itemPlaces' | 'containerPlaces',
    id: string,
    placeId: string | null,
  ): Promise<TravelProfile> {
    this.#authorize(caller);
    if (placeId !== null) await Place.assertOwn(caller, placeId);
    return this.#asStored(
      await (
        await getTravelProfileRepository()
      ).setPin(this.workspaceId, this.ownerUserId, map, id, placeId),
    );
  }

  /** The profile as now stored (404 when it went meanwhile: the membership ended). */
  #asStored(row: TravelProfileData | null): TravelProfile {
    if (row === null) throw new NotFoundError();
    return new TravelProfile(row);
  }

  /** 404 unless it is the caller's own profile (here); then the editor check (403). */
  #authorize(caller: Caller): void {
    this.assertIn(caller);
    if (!this.isOwnedBy(caller.userId)) throw new NotFoundError();
    caller.require('editor');
  }
}
